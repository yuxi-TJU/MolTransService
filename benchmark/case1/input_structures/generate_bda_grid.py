#!/usr/bin/env python3
"""Generate the 19 x 19 BDA torsion scan used for Case 1.

The archived scan labels rotations relative to the supplied reference geometry.
A positive ``theta`` increases the signed inter-ring dihedral, whereas a
positive ``phi`` decreases both signed terminal-group dihedrals.  This
convention reproduces the structures used in the reported calculations.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable, Sequence

import numpy as np


THETA_DIHEDRAL = (8, 12, 13, 16)  # 0-indexed form of (9,13,14,17)
THETA_AXIS = (12, 13)  # atoms 13-14
THETA_GROUP = tuple(range(13, 26))  # atoms 14-26

PHI_LEFT_DIHEDRAL = (0, 2, 3, 6)  # (1,3,4,7)
PHI_LEFT_AXIS = (2, 3)  # atoms 3-4
PHI_LEFT_GROUP = (0, 1, 2)  # atoms [1,2,3]

PHI_RIGHT_DIHEDRAL = (24, 23, 22, 18)  # (25,24,23,19)
PHI_RIGHT_AXIS = (23, 22)  # atoms 24-23
PHI_RIGHT_GROUP = (23, 24, 25)  # atoms [24,25,26]

THETA_VALUES = tuple(range(0, 91, 5))
PHI_VALUES = tuple(range(0, 181, 10))


def read_xyz(path: Path) -> tuple[list[str], np.ndarray]:
    text = path.read_text().strip().splitlines()
    atom_count = int(text[0].strip())
    if len(text) < atom_count + 2:
        raise ValueError(f"{path} does not contain {atom_count} atoms.")
    symbols: list[str] = []
    coords = []
    for line in text[2 : 2 + atom_count]:
        parts = line.split()
        if len(parts) < 4:
            raise ValueError(f"Failed to parse coordinate line: {line}")
        symbols.append(parts[0])
        coords.append([float(parts[1]), float(parts[2]), float(parts[3])])
    return symbols, np.array(coords, dtype=float)


def write_xyz(path: Path, symbols: Sequence[str], coords: np.ndarray, theta: int, phi: int) -> None:
    header = f"Generated by generate_bda_grid.py | theta={theta} phi={phi}"
    lines = [str(len(symbols)), header]
    for symbol, (x, y, z) in zip(symbols, coords):
        lines.append(f"{symbol:2s} {x:14.8f} {y:14.8f} {z:14.8f}")
    path.write_text("\n".join(lines) + "\n")


def torsion_angle(coords: np.ndarray, atoms: Sequence[int]) -> float:
    i, j, k, l = atoms
    p0, p1, p2, p3 = coords[[i, j, k, l]]
    b0 = p0 - p1
    b1 = p2 - p1
    b2 = p3 - p2
    b1 /= np.linalg.norm(b1)
    v = b0 - np.dot(b0, b1) * b1
    w = b2 - np.dot(b2, b1) * b1
    x = np.dot(v, w)
    y = np.dot(np.cross(b1, v), w)
    return float(np.degrees(np.arctan2(y, x)))


def wrap_angle(angle: float) -> float:
    return (angle + 180.0) % 360.0 - 180.0


def rotate_group(coords: np.ndarray, axis: Sequence[int], group: Iterable[int], angle_deg: float) -> None:
    if abs(angle_deg) < 1e-9:
        return
    i, j = axis
    origin = coords[i]
    axis_vec = coords[j] - origin
    axis_norm = np.linalg.norm(axis_vec)
    if axis_norm == 0:
        raise ValueError("Rotation axis has zero length.")
    axis_unit = axis_vec / axis_norm
    angle_rad = np.deg2rad(angle_deg)
    cos_ang = np.cos(angle_rad)
    sin_ang = np.sin(angle_rad)
    for idx in set(group):
        vec = coords[idx] - origin
        rotated = (
            vec * cos_ang
            + np.cross(axis_unit, vec) * sin_ang
            + axis_unit * np.dot(axis_unit, vec) * (1 - cos_ang)
        )
        coords[idx] = rotated + origin


def rotation_sense(coords: np.ndarray, torsion: Sequence[int], axis: Sequence[int], group: Iterable[int]) -> float:
    """Return +1 if positive rotation increases torsion, else -1."""
    before = torsion_angle(coords, torsion)
    for trial_angle in (1.0, -1.0):
        probe = np.array(coords, copy=True)
        rotate_group(probe, axis, group, trial_angle)
        after = torsion_angle(probe, torsion)
        delta = wrap_angle(after - before)
        if abs(delta) > 1e-6:
            return 1.0 if delta > 0 else -1.0
    raise RuntimeError(f"Rotation about axis {axis} does not affect torsion {torsion}.")


def set_dihedral(
    coords: np.ndarray,
    torsion: Sequence[int],
    axis: Sequence[int],
    group: Iterable[int],
    target_deg: float,
    tol: float = 1e-4,
) -> None:
    sense = rotation_sense(coords, torsion, axis, group)
    for _ in range(10):
        current = torsion_angle(coords, torsion)
        diff = wrap_angle(target_deg - current)
        if abs(diff) < tol:
            return
        rotate_group(coords, axis, group, diff * sense)
    final = torsion_angle(coords, torsion)
    raise RuntimeError(f"Failed to set torsion {torsion} to {target_deg}°, reached {final:.3f}° instead.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=Path("theta_000_phi_000.xyz"), help="Input XYZ template.")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("structures"),
        help="Output directory for scan files (default: structures).",
    )
    parser.add_argument("--skip-existing", action="store_true", help="Skip writing files that already exist.")
    args = parser.parse_args()

    symbols, base_coords = read_xyz(args.input)
    args.output.mkdir(parents=True, exist_ok=True)

    theta_reference = torsion_angle(base_coords, THETA_DIHEDRAL)
    phi_left_reference = torsion_angle(base_coords, PHI_LEFT_DIHEDRAL)
    phi_right_reference = torsion_angle(base_coords, PHI_RIGHT_DIHEDRAL)

    for theta in THETA_VALUES:
        for phi in PHI_VALUES:
            coords = np.array(base_coords, copy=True)
            set_dihedral(
                coords,
                THETA_DIHEDRAL,
                THETA_AXIS,
                THETA_GROUP,
                theta_reference + float(theta),
            )
            set_dihedral(
                coords,
                PHI_LEFT_DIHEDRAL,
                PHI_LEFT_AXIS,
                PHI_LEFT_GROUP,
                phi_left_reference - float(phi),
            )
            set_dihedral(
                coords,
                PHI_RIGHT_DIHEDRAL,
                PHI_RIGHT_AXIS,
                PHI_RIGHT_GROUP,
                phi_right_reference - float(phi),
            )
            outfile = args.output / f"theta_{theta:03d}_phi_{phi:03d}.xyz"
            if args.skip_existing and outfile.exists():
                continue
            write_xyz(outfile, symbols, coords, theta, phi)


if __name__ == "__main__":
    main()
